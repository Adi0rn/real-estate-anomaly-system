async function verifyAll() {
  const distinct = Array.from(new Set(knownIds));
  console.log(`Checking ${distinct.length} distinct photo IDs...`);
  const working: string[] = [];

  for (const id of distinct) {
    const url = `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=1200&q=80`;
    try {
      const res = await fetch(url, { method: "HEAD" });
      if (res.status >= 200 && res.status < 400) {
        working.push(id);
      }
    } catch {}
  }

  console.log(`Working distinct IDs: ${working.length}`);
  const fs = await import("fs");
  fs.writeFileSync("scripts/working-ids.json", JSON.stringify(working, null, 2));
}

verifyAll();
